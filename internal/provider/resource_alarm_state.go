func (r *AlarmStateResource) Configure(_ context.Context, req resource.ConfigureRequest, resp *resource.ConfigureResponse) {
	if req.ProviderData == nil {
		return
	}
	c, err := GetClientFromProviderData(req.ProviderData)
	if err != nil {
		resp.Diagnostics.AddError("Unexpected provider data type", err.Error())
		return
	}
	r.client = c
}

func (r *AlarmStateResource) Create(ctx context.Context, req resource.CreateRequest, resp *resource.CreateResponse) {
	var data AlarmStateResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}

	if err := r.updateState(ctx, &data); err != nil {
		resp.Diagnostics.AddError("Error updating alarm instance state", err.Error())
		return
	}
	if err := r.readInstance(ctx, &data); err != nil {
		resp.Diagnostics.AddError("Error reading alarm instance after updating its state", err.Error())
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

func (r *AlarmStateResource) Read(ctx context.Context, req resource.ReadRequest, resp *resource.ReadResponse) {
	var data AlarmStateResourceModel
	resp.Diagnostics.Append(req.State.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}

	if err := r.readInstance(ctx, &data); err != nil {
		if err == errAlarmInstanceNotFound {
			resp.State.RemoveResource(ctx)
			return
		}
		resp.Diagnostics.AddError("Error reading alarm instance", err.Error())
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

func (r *AlarmStateResource) Update(ctx context.Context, req resource.UpdateRequest, resp *resource.UpdateResponse) {
	var data AlarmStateResourceModel
	resp.Diagnostics.Append(req.Plan.Get(ctx, &data)...)
	if resp.Diagnostics.HasError() {
		return
	}

	if err := r.updateState(ctx, &data); err != nil {
		resp.Diagnostics.AddError("Error updating alarm instance state", err.Error())
		return
	}
	if err := r.readInstance(ctx, &data); err != nil {
		resp.Diagnostics.AddError("Error reading alarm instance after updating its state", err.Error())
		return
	}

	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

// Delete removes the resource from Terraform state only: there is no API to
// undo an alarm acknowledgement/suppression or delete an alarm instance.
func (r *AlarmStateResource) Delete(_ context.Context, _ resource.DeleteRequest, _ *resource.DeleteResponse) {
}

func (r *AlarmStateResource) ImportState(ctx context.Context, req resource.ImportStateRequest, resp *resource.ImportStateResponse) {
	var data AlarmStateResourceModel
	data.ID = types.StringValue(req.ID)
	if err := r.readInstance(ctx, &data); err != nil {
		resp.Diagnostics.AddError("Error importing alarm instance", err.Error())
		return
	}
	resp.Diagnostics.Append(resp.State.Set(ctx, &data)...)
}

var errAlarmInstanceNotFound = fmt.Errorf("alarm instance not found")

func (r *AlarmStateResource) updateState(ctx context.Context, data *AlarmStateResourceModel) error {
	values := url.Values{}
	values.Set("updated_state", data.DesiredState.ValueString())
	if !data.SuppressDuration.IsNull() {
		values.Set("suppress_duration", strconv.FormatInt(data.SuppressDuration.ValueInt64(), 10))
	}

	body := client.UpdateAlarmInstancesRequest{Instances: []string{data.ID.ValueString()}}
	_, err := r.client.Post(ctx, "/ssp/alarms/states?"+values.Encode(), &body, nil)
	if err != nil {
		return fmt.Errorf("POST /ssp/alarms/states: %w", err)
	}
	return nil
}

func (r *AlarmStateResource) readInstance(ctx context.Context, data *AlarmStateResourceModel) error {
	id := data.ID.ValueString()
	var instance client.AlarmInstance
	httpStatus, err := r.client.Get(ctx, "/ssp/alarms/"+id, &instance)
	if httpStatus == 404 {
		return errAlarmInstanceNotFound
	}
	if err != nil {
		return fmt.Errorf("GET /ssp/alarms/%s: %w", id, err)
	}

	data.ID = types.StringValue(id)
	data.State = types.StringValue(instance.State)
	data.FeatureName = types.StringValue(instance.FeatureName)
	data.Severity = types.StringValue(instance.Severity)
	data.Summary = types.StringValue(instance.Summary)
	data.Description = types.StringValue(instance.Description)
	data.RecommendedAction = types.StringValue(instance.RecommendedAction)
	data.ResourceID = types.StringValue(instance.ResourceID)
	data.Value = types.StringValue(instance.Value)
	return nil
}
