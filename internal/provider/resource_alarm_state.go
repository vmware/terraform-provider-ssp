var _ resource.Resource = &AlarmStateResource{}
var _ resource.ResourceWithImportState = &AlarmStateResource{}

func NewAlarmStateResource() resource.Resource {
	return &AlarmStateResource{}
}

// AlarmStateResource manages the acknowledgement/suppression of a pre-existing
// alarm instance by ID. Alarm instances are created by the platform, not by
// this resource — there is no POST/DELETE to create or remove one.
type AlarmStateResource struct {
	client *client.Client
}

type AlarmStateResourceModel struct {
	ID                types.String `tfsdk:"id"`
	DesiredState      types.String `tfsdk:"desired_state"`
	SuppressDuration  types.Int64  `tfsdk:"suppress_duration"`
	State             types.String `tfsdk:"state"`
	FeatureName       types.String `tfsdk:"feature_name"`
	Severity          types.String `tfsdk:"severity"`
	Summary           types.String `tfsdk:"summary"`
	Description       types.String `tfsdk:"description"`
	RecommendedAction types.String `tfsdk:"recommended_action"`
	ResourceID        types.String `tfsdk:"resource_id"`
	Value             types.String `tfsdk:"value"`
}

func (r *AlarmStateResource) Metadata(_ context.Context, req resource.MetadataRequest, resp *resource.MetadataResponse) {
	resp.TypeName = req.ProviderTypeName + "_alarm_state"
}

